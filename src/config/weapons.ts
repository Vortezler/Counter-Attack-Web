export const shop = { ...catalog, ...gear };
export function isGun(key: string): key is Gun {
  return Object.hasOwn(catalog, key);
}
export function weaponName(key: Weapon) {
  return key === "bomb" ? "C4" : shop[key].name;
}
export function magazine(id: Gun) {
  return {
    id,
    ammo: Number(catalog[id].mag),
    reserve: Number(catalog[id].reserve),
  };
}
export type Magazine = ReturnType<typeof magazine>;
